def detect_region(text: str) -> str:
    """يستخرج تلميحًا للمنطقة من نص الطلب (إن ذُكرت) لإضافة لون محلي."""
    blob = (text or '')
    for key, hint in REGION_HINTS.items():
        if key in blob:
            return hint
    return ''


